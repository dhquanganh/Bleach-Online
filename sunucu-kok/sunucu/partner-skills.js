function unlocked(state,heroId,options={}){
  const row=satir('HeroChangeAttr',heroId);
  const ids=row?json(row.chipID):[];
  const count=Math.max(0,Math.min(ids.length,Math.floor(Number(state.degisim&&state.degisim.hero&&state.degisim.hero[heroId])||0)));
  const out=[];
  for(const id of ids.slice(0,count)){const change=satir('PartnerChange',id);for(const effect of change?json(change.effect):[])if(Number(effect.addType)>=200)out.push(Number(effect.addValue));}
  if(options.pvp&&Number(require('./seviye').veriOku().level)>=45)for(const a of require('./zanpakuto').phase(state,heroId)){if(Number(a.oper)===0&&definitions.has(Number(a.value)))out.push(Number(a.value));}
  return [...new Set(out)];
}
function trigger(event,caster,allies,enemies,targets,records,random=Math.random){
  for(const id of caster.partnerSkills||[]){const entry=definitions.get(id),definition=entry&&entry.events[event];if(!definition)continue;
    const procResults=new Map();
    const rules=definition.effects.filter(rule=>(!rule.pvpOnly||caster.pvp)&&(!rule.limit||(caster.battleRound||1)<=rule.limit)&&(rule.kind==='buff'||rule.threshold==null||caster.hp/caster.maxHp<rule.threshold)).filter(rule=>{
      if(rule.chance==null||rule.chance>=1)return true;
      // One passive proc affects the whole selected group; do not roll a
      // whole-team shield separately for each ally or split its paired bonuses.
      const key=`${rule.scope}:${rule.chance}`;
      if(!procResults.has(key))procResults.set(key,random()<rule.chance);
      return procResults.get(key);
    }).map(rule=>({...rule,chance:1}));
    engine.apply({sourceId:id,effects:rules},caster,allies,enemies,targets,records,random);
  }
}
